"""rsyslog remote-capture generator (per-net remote syslog design).

One imudp input per served router leg, all on UDP 514 — the log class is
the net the message arrives on. Messages are written to
/var/log/<netname>/<name>.log via a per-net dynafile ruleset.

<name> is the sending IP's sheet hostname, looked up in the generated
remote-logs.names.json table (see _sender_names) — never the hostname a
device claims in its header (BMCs say "ATEN", switches append "-1") nor
its PTR (ipv4.<host>.<net>.<domain>). An IP missing from the table is
written to unknown-<ip>.log, so an unexpected sender is visible rather
than merged into some other device's file.

Served nets = the router's leaf-net legs (recursor_forward._leaf_gateways,
i.e. the same derivation as the DNS leaf gateways) minus the untrusted
tmp/guest nets. v4 only — every current sender targets v4.

Safety properties (carried over from the hand-written files this
replaces): remote messages only reach the per-device files (ruleset
isolation + stop), never /var/log/syslog; local messages never reach the
remote dirs; file names come from the generated table (sheet hostnames
or unknown-<ip>), and secpath-replace stays on as defence in depth;
dynafile dirs are auto-created (0755, files root:adm 0640).

Kernel netconsole capture rides the same file: one leg-bound imudp input
per served net on UDP 6666 (the fleet's netconsole port), ruleset
remote-<net>-kernel, files /var/log/<net>/<name>.kernel.log, named from the
same table so they sit beside the sender's syslog file. Netconsole
payloads are raw printk — no syslog header, no hostname — and the
shared KernelLine template stamps wall-clock arrival next to the raw
payload (whose level,seq,monotonic-ts prefix survives for gap
detection). Receive-only for now: the pucks still stream to wisp:6666;
re-pointing them (and retiring wisp's receiver) is a documented
follow-up.
"""

from __future__ import annotations

import ipaddress
import json

from gdoc2netcfg.generators.recursor_forward import _leaf_gateways
from gdoc2netcfg.models.host import Host, NetworkInventory

# Untrusted nets never get a syslog input.
EXCLUDED_NETS = frozenset({"tmp", "guest"})

_HEADER = """\
# Generated by gdoc2netcfg (rsyslog) — do not edit.
# Per-net remote syslog capture: one imudp input per router leg, all on
# UDP 514; the class is the net the message arrives on. Replaces the
# hand-written tasmota.conf + z-network-switches.conf (this file now
# performs the single allowed imudp module load).
module(load="imudp")

# Sending IP -> sheet hostname (generated alongside this file). Every
# ruleset names its files from it; an IP not in it logs to unknown-<ip>.
lookup_table(name="remote-names"
             file="/etc/rsyslog.d/remote-logs.names.json" reloadOnHUP="on")

# Kernel netconsole capture: raw printk datagrams (no syslog header, no
# hostname) arrive on UDP 6666, one leg-bound input per served net.
# Each line is stamped with wall-clock arrival time (the payload carries
# only the extended netconsole level,seq,monotonic-ts prefix, preserved
# for gap detection).
template(name="KernelLine" type="string"
         string="%timegenerated:::date-rfc3339% %rawmsg:::drop-last-lf%\\n")
"""


def _served_legs(inventory: NetworkInventory) -> dict[str, str]:
    """net -> the router's v4 leg address, tmp/guest excluded."""
    legs: dict[str, str] = {}
    for net, forwarders in _leaf_gateways(inventory).items():
        if net in EXCLUDED_NETS:
            continue
        v4 = [a for a in forwarders if ":" not in a]
        if not v4:
            raise ValueError(
                f"rsyslog generator: net {net!r} leg has no IPv4 address — "
                "expected every leaf leg to carry a v4 address"
            )
        legs[net] = v4[0]
    return legs


def _sender_names(inventory: NetworkInventory) -> dict[str, str]:
    """Every host IPv4 -> the sheet hostname its log files are named by.

    v4 only, like the inputs: a v6 key could never match $fromhost-ip.
    An IP owned by several hosts is acceptable only as a cross-sheet
    mirror (one machine recorded on the Network sheet and again on another
    sheet, see constraints.validators._is_cross_sheet_mirror), and names
    the Network-sheet host. Anything else would have failed validation
    before the data was cached, so it is asserted, not handled.
    """
    owners: dict[str, list[Host]] = {}
    for host in inventory.hosts:
        for iface in host.interfaces:
            ip = str(iface.ipv4)
            if not any(h is host for h in owners.get(ip, [])):
                owners.setdefault(ip, []).append(host)

    names: dict[str, str] = {}
    for ip, hosts in owners.items():
        if len(hosts) == 1:
            names[ip] = hosts[0].hostname
            continue
        network = [h for h in hosts if h.sheet_type == "Network"]
        is_mirror = (
            len({h.machine_name for h in hosts}) == 1
            and len({h.sheet_type for h in hosts}) == len(hosts)
            and len(network) == 1
        )
        assert is_mirror, (
            f"rsyslog generator: {ip} is owned by "
            f"{', '.join(sorted(h.hostname for h in hosts))}; validation "
            "should have rejected this before the data was cached"
        )
        names[ip] = network[0].hostname
    return names


def _names_table(names: dict[str, str]) -> str:
    """The rsyslog lookup_table JSON, rows in numeric IP order."""
    rows = [
        {"index": ip, "value": names[ip]}
        for ip in sorted(names, key=ipaddress.IPv4Address)
    ]
    return json.dumps(
        {"version": 1, "nomatch": "", "type": "string", "table": rows},
        indent=1,
    ) + "\n"


# Shared head of every ruleset: the file name for the sending IP. The
# table's nomatch is "", so a sender it does not know gets unknown-<ip>.
_LOOKUP_NAME = """\
    set $.name = lookup("remote-names", $fromhost-ip);
    if $.name == "" then {
        set $.name = "unknown-" & $fromhost-ip;
    }
"""


# Mail alerts ([generators.rsyslog] alert_* keys; all or none).
ALERT_KEYS = (
    "alert_mail_to", "alert_mail_from", "alert_smtp_server",
    "alert_smtp_port", "alert_interval", "alert_unknown_interval",
)

# Subjects. A Supermicro BMC line reads
#   ipmi: Health EventLog | <time> | <ip> | Critical | IERR - Assertion | ...
# so the subject takes the severity and the event after it. Verified on
# rsyslog 8.2608 against the 2026-10-20 big-storage IERR (tmp/ommail_probe.py):
# "[syslog] bmc.big-storage: Critical IERR - Assertion".
# Device text reaches the subject and body, so header injection relies on
# rsyslog's default escapeControlCharactersOnReceive="on": CR/LF arrive as
# #015#012 (verified in review with an SMTP-smuggling payload). Do not
# turn that global off.
_SEVERITY = "%msg:R,ERE,1,FIELD:[|] (Critical|Warning) [|]--end%"
_EVENT = "%msg:R,ERE,2,FIELD:[|] (Critical|Warning) [|] ([^|]*[^| ])--end%"
_ALERT_TEMPLATES = f"""\
module(load="ommail")
template(name="AlertSubjectBmc" type="string"
         string="[syslog] %$.name%: {_SEVERITY} {_EVENT}")
template(name="AlertSubjectUnknown" type="string"
         string="[syslog] unknown sender %fromhost-ip%")
template(name="AlertBody" type="string"
         string="%timegenerated:::date-rfc3339% %fromhost-ip% (%$.name%)\\r\\n%rawmsg%\\r\\n")
"""


def _alert_settings(
    params: dict[str, str | int | None],
) -> dict[str, str] | None:
    """The alert_* settings as strings, or None when alerts are off.

    All or none: a half-configured alerter (no recipient, no relay) would
    fail only when the alert it exists for finally fires. The port and
    interval may come from the toml as integers.
    """
    given = {k: str(v) for k, v in params.items() if v is not None and v != ""}
    if not given:
        return None
    missing = [k for k in ALERT_KEYS if k not in given]
    if missing:
        raise ValueError(
            "rsyslog generator: [generators.rsyslog] sets some alert_* keys "
            f"but not {', '.join(missing)}; set all of {', '.join(ALERT_KEYS)} "
            "or none"
        )
    for key, low, high in (
        ("alert_interval", 1, None),
        ("alert_unknown_interval", 1, None),
        ("alert_smtp_port", 1, 65535),
    ):
        value = given[key]
        if not value.isdigit() or int(value) < low or (high and int(value) > high):
            raise ValueError(
                f"rsyslog generator: {key} must be a whole number "
                f"{low}-{high or 'up'}, got {params[key]!r}"
            )
    return given


def _mail_action(alerts: dict[str, str], subject: str, spool: str,
                 interval: str | None) -> str:
    """One ommail action.

    Its queue is its own (an SMTP outage never stalls the file write) and
    disk-assisted under rsyslog's work directory, saved on shutdown, so a
    mail queued during an outage survives a restart. execOnlyOnceEveryInterval
    is per ACTION, not per sender or event: every mail it suppresses is
    another line matching the same rule on the same net, so each rule gets
    its own action and interval=None means every match is mailed.
    """
    limit = (f'\n               action.execOnlyOnceEveryInterval="{interval}"'
             if interval is not None else "")
    return f"""\
        action(type="ommail"
               server="{alerts['alert_smtp_server']}" port="{alerts['alert_smtp_port']}"
               mailfrom="{alerts['alert_mail_from']}" mailto="{alerts['alert_mail_to']}"
               subject.template="{subject}" template="AlertBody"{limit}
               queue.type="LinkedList" queue.size="1000"
               queue.filename="{spool}" queue.saveOnShutdown="on"
               queue.maxDiskSpace="10m"
               action.resumeRetryCount="-1" action.resumeInterval="30")
"""


def _unknown_alert(alerts: dict[str, str] | None, ruleset: str) -> str:
    """A sender missing from the name table; it keeps sending, so this one
    is limited by its own, long alert_unknown_interval."""
    if alerts is None:
        return ""
    return ('    if $.name startswith "unknown-" then {\n'
            + _mail_action(alerts, "AlertSubjectUnknown",
                           f"alert-unknown-{ruleset}",
                           alerts["alert_unknown_interval"])
            + "    }\n")


def _bmc_ips(inventory: NetworkInventory) -> list[str]:
    """The IPv4s of every host the sheet marks as a BMC, in numeric order."""
    ips = {str(iface.ipv4) for host in inventory.hosts if host.is_bmc
           for iface in host.interfaces}
    return sorted(ips, key=ipaddress.IPv4Address)


def _bmc_alert(alerts: dict[str, str] | None, net: str, bmc_ips: list[str]) -> str:
    """Supermicro BMC Health events, from sheet-marked BMCs only.

    Critical is never rate-limited: the survey of all history found one
    Critical in 68,760 BMC lines, and a suppressed one is the failure this
    alert exists to prevent. So only a BMC's own address may trigger it;
    any other device on a served net could otherwise flood mail with a
    forged "Health EventLog | Critical |" datagram (forging the BMC's
    source address on the LAN remains possible, but is far harder).
    """
    if alerts is None or not bmc_ips:
        return ""
    senders = " or ".join(f'$fromhost-ip == "{ip}"' for ip in bmc_ips)
    if len(bmc_ips) > 1:
        senders = f"({senders})"
    out = []
    for severity, interval in (("Critical", None), ("Warning", alerts["alert_interval"])):
        out.append(
            f'    if {senders} and $msg contains "Health EventLog" and '
            f'$msg contains "| {severity} |" then {{\n'
            + _mail_action(alerts, "AlertSubjectBmc",
                           f"alert-{severity.lower()}-{net}", interval)
            + "    }\n")
    return "".join(out)


def _net_block(net: str, addr: str, alerts: dict[str, str] | None,
               bmc_ips: list[str]) -> str:
    """Template + ruleset + leg-bound :514 input for one served net."""
    return f"""\
template(name="RemoteLog-{net}" type="string"
         string="/var/log/{net}/%$.name:::secpath-replace%.log")
ruleset(name="remote-{net}") {{
{_LOOKUP_NAME}    action(type="omfile" dynaFile="RemoteLog-{net}"
           fileOwner="root" fileGroup="adm"
           fileCreateMode="0640" dirCreateMode="0755")
{_bmc_alert(alerts, net, bmc_ips)}{_unknown_alert(alerts, net)}    stop
}}
input(type="imudp" port="514" address="{addr}" ruleset="remote-{net}")
"""


def _kernel_block(net: str, addr: str, alerts: dict[str, str] | None) -> str:
    """Netconsole template + ruleset + leg-bound :6666 input for one net."""
    return f"""\
template(name="KernelLog-{net}" type="string"
         string="/var/log/{net}/%$.name:::secpath-replace%.kernel.log")
ruleset(name="remote-{net}-kernel") {{
{_LOOKUP_NAME}    action(type="omfile" dynaFile="KernelLog-{net}" template="KernelLine"
           fileOwner="root" fileGroup="adm"
           fileCreateMode="0640" dirCreateMode="0755")
{_unknown_alert(alerts, f"{net}-kernel")}    stop
}}
input(type="imudp" port="6666" address="{addr}" ruleset="remote-{net}-kernel")
"""


_LOGROTATE_HEADER = """\
# Generated by gdoc2netcfg (rsyslog) — do not edit.
# Retention: keep at least one year of daily logs. `notifempty` skips days
# a device sent nothing, so 400 daily archives span >=400 days for a
# chatty device and longer for an intermittent one, comfortably clearing
# the 1-year floor. No maxage: nothing is removed by age, only once the
# count is exceeded.
"""


def _logrotate(nets: list[str]) -> str:
    """One 1-year-floor logrotate stanza per served net's log dir."""
    stanzas = [_LOGROTATE_HEADER]
    for net in nets:
        stanzas.append(f"""\
/var/log/{net}/*.log {{
    daily
    rotate 400
    compress
    delaycompress
    missingok
    notifempty
    postrotate
        /usr/lib/rsyslog/rsyslog-rotate
    endscript
}}
""")
    return "\n".join(stanzas)


def generate_rsyslog(
    inventory: NetworkInventory,
    alert_mail_to: str | None = None,
    alert_mail_from: str | None = None,
    alert_smtp_server: str | None = None,
    alert_smtp_port: str | int | None = None,
    alert_interval: str | int | None = None,
    alert_unknown_interval: str | int | None = None,
) -> dict[str, str]:
    """Generate the rsyslog drop-in + logrotate file.

    With the alert_* settings, each net's syslog ruleset also mails a
    BMC Health Critical/Warning line, and every ruleset mails a sender
    missing from the name table (unknown-<ip>).

    Returns deploy-relative paths under etc/ ([generators.rsyslog]
    output_dir = "etc"): rsyslog.d/remote-logs.conf, its sender-name
    table rsyslog.d/remote-logs.names.json, and logrotate.d/remote-logs.
    """
    legs = _served_legs(inventory)
    if not legs:
        raise ValueError(
            "rsyslog generator: router has no served legs — check the "
            "inventory has a 'ten64' host with leaf-net interfaces"
        )
    alerts = _alert_settings({
        "alert_mail_to": alert_mail_to,
        "alert_mail_from": alert_mail_from,
        "alert_smtp_server": alert_smtp_server,
        "alert_smtp_port": alert_smtp_port,
        "alert_interval": alert_interval,
        "alert_unknown_interval": alert_unknown_interval,
    })
    bmc_ips = _bmc_ips(inventory)
    parts = [_HEADER]
    if alerts is not None:
        parts.append(_ALERT_TEMPLATES)
    for net in sorted(legs):
        parts.append(_net_block(net, legs[net], alerts, bmc_ips))
        parts.append(_kernel_block(net, legs[net], alerts))
    return {
        "rsyslog.d/remote-logs.conf": "\n".join(parts),
        "rsyslog.d/remote-logs.names.json":
            _names_table(_sender_names(inventory)),
        "logrotate.d/remote-logs": _logrotate(sorted(legs)),
    }
